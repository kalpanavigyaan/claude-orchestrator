pub fn ok_result(data: serde_json::Value) -> ToolResult {
    ToolResult {
        ok: true,
        error: String::new(),
        data: Some(json_to_struct(data)),
        text: String::new(),
    }
}

pub fn err_result(msg: &str) -> ToolResult {
    ToolResult {
        ok: false,
        error: msg.to_string(),
        data: None,
        text: String::new(),
    }
}

pub fn ok_text(text: String) -> ToolResult {
    ToolResult {
        ok: true,
        error: String::new(),
        data: None,
        text,
    }
}

pub fn json_to_struct(v: serde_json::Value) -> prost_types::Struct {
    use prost_types::value::Kind;
    use prost_types::{Value as PValue, ListValue};

    fn convert(v: serde_json::Value) -> PValue {
        PValue {
            kind: Some(match v {
                serde_json::Value::Null => Kind::NullValue(0),
                serde_json::Value::Bool(b) => Kind::BoolValue(b),
                serde_json::Value::Number(n) => Kind::NumberValue(n.as_f64().unwrap_or(0.0)),
                serde_json::Value::String(s) => Kind::StringValue(s),
                serde_json::Value::Array(arr) => Kind::ListValue(ListValue {
                    values: arr.into_iter().map(convert).collect(),
                }),
                serde_json::Value::Object(map) => Kind::StructValue(prost_types::Struct {
                    fields: map.into_iter().map(|(k, v)| (k, convert(v))).collect(),
                }),
            }),
        }
    }

    if let serde_json::Value::Object(map) = v {
        prost_types::Struct {
            fields: map.into_iter().map(|(k, v)| (k, convert(v))).collect(),
        }
    } else {
        prost_types::Struct {
            fields: [("value".to_string(), convert(v))].into_iter().collect(),
        }
    }
}
